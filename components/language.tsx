type LanguageContextValue={language:Language;setLanguage:(language:Language)=>void;t:(english:string)=>string};
const LanguageContext=createContext<LanguageContextValue>({language:"en",setLanguage:()=>{},t:value=>value});

export function LanguageProvider({children}:{children:ReactNode}){
  const[language,setLanguageState]=useState<Language>("en");
  useEffect(()=>{const saved=localStorage.getItem(LANGUAGE_STORE),timer=saved==="sq"?window.setTimeout(()=>setLanguageState("sq"),0):null;return()=>{if(timer!==null)window.clearTimeout(timer)}},[]);
  useEffect(()=>{document.documentElement.lang=language;localStorage.setItem(LANGUAGE_STORE,language)},[language]);
  const setLanguage=useCallback((next:Language)=>setLanguageState(next),[]),t=useCallback((english:string)=>language==="sq"?(sq[english]??english):english,[language]);
  const value=useMemo(()=>({language,setLanguage,t}),[language,setLanguage,t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

