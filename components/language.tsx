export function LanguageToggle({compact=false}:{compact?:boolean}){
  const{language,setLanguage,t}=useLanguage();
  return <div className="flex items-center rounded-lg border border-white/15 bg-black/25 p-0.5" role="group" aria-label={t("Language")} title={t("Language")}>
    <button type="button" onClick={()=>setLanguage("en")} aria-pressed={language==="en"} className={`rounded-md px-2 py-1 text-[11px] font-semibold tracking-wider transition ${language==="en"?"bg-amber-100 text-stone-950":"text-slate-400 hover:text-white"}`}>{compact?"EN":"EN"}</button>
    <button type="button" onClick={()=>setLanguage("sq")} aria-pressed={language==="sq"} className={`rounded-md px-2 py-1 text-[11px] font-semibold tracking-wider transition ${language==="sq"?"bg-amber-100 text-stone-950":"text-slate-400 hover:text-white"}`}>SH</button>
  </div>;
}
